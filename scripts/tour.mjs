// Dev helper: enters the world and photographs key places. Usage: node scripts/tour.mjs <outDir>
import { chromium } from '@playwright/test'

const out = process.argv[2] || '.'
const url = process.argv[3] || 'http://localhost:5173/'
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } })
const logs = []
page.on('console', (m) => m.type() !== 'debug' && logs.push(`[${m.type()}] ${m.text()}`))
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`))
await page.goto(url)
await page.getByTestId('role-me').click()
const inputs = page.locator('.q-list input')
await inputs.nth(0).fill('Our Little World!')
await inputs.nth(1).fill('hers')
await page.getByTestId('questions-continue').click()
await page.getByTestId('enter').click()
await page.waitForSelector('.loading.done', { timeout: 90000, state: 'attached' })
const tp = (x, z, yaw, camYaw) => page.evaluate(([x, z, yaw, camYaw]) => (window.__olw.live.teleport = { x, z, yaw, camYaw }), [x, z, yaw, camYaw])
const shot = async (name, wait = 2500) => {
  await page.waitForTimeout(wait)
  await page.screenshot({ path: `${out}/${name}.png` })
}
const fps = () => page.evaluate(() => new Promise((r) => { let n = 0; const t0 = performance.now(); const f = () => { n++; if (performance.now() - t0 < 2000) requestAnimationFrame(f); else r(n / 2) }; requestAnimationFrame(f) }))
await shot('10-intro', 5000)
console.log('fps', await fps())
await tp(0, 3.7, Math.PI)
await shot('11-cake')
await page.keyboard.press('KeyE')
await shot('12-cake-blown', 1500)
await shot('13-cake-after', 2500)
await tp(0, -12, Math.PI)
await shot('14-house-outside')
await tp(0, -22.5, Math.PI)
await shot('15-hall')
await tp(-5.6, -26, -Math.PI / 2)
await shot('16-left-wall')
await page.keyboard.press('KeyE')
await shot('17-photo', 1500)
await page.keyboard.press('ArrowRight')
await shot('18-photo-next', 1200)
await page.keyboard.press('Escape')
await tp(0, -31.2, Math.PI)
await shot('19-portal')
await page.keyboard.press('KeyE')
await page.waitForTimeout(500)
await page.getByTestId('portal-answer').fill('guitar')
await page.getByTestId('portal-submit').click()
await shot('20-portal-wrong', 800)
await page.getByTestId('portal-answer').fill('  Piano! ')
await page.getByTestId('portal-submit').click()
await shot('21-portal-open', 700)
await shot('22-letter', 4000)
await page.keyboard.press('Escape')
await tp(3, -24, Math.PI * 0.8, Math.PI * 0.8)
await shot('23-hall-wide')
console.log(logs.slice(0, 40).join('\n'))
await browser.close()
